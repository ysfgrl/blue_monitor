import 'dart:io';

import 'package:pigeon/ast.dart';
import 'package:pigeon/generator_tools.dart';
import 'package:pigeon/pigeon.dart';

import '../pigeon/messages.dart' as configuration;

/// Linux and Windows generate host APIs and all message types. Their event
/// channels must be registered by the native plugin using the generated codec.
/// Keep the full root for Dart/Kotlin/Swift so their events are still generated.
class DesktopGeneratorAdapter implements GeneratorAdapter {
  DesktopGeneratorAdapter(this.delegate);

  final GeneratorAdapter delegate;

  Root _withoutEventChannels(Root root) => Root(
    classes: root.classes,
    enums: root.enums,
    apis: root.apis.where((api) => api is! AstEventChannelApi).toList(),
    containsHostApi: root.containsHostApi,
    containsFlutterApi: root.containsFlutterApi,
    containsProxyApi: root.containsProxyApi,
  );

  @override
  List<FileType> get fileTypeList => delegate.fileTypeList;

  @override
  set fileTypeList(List<FileType> value) => delegate.fileTypeList = value;

  @override
  IOSink? shouldGenerate(PigeonOptions options, FileType type) =>
      delegate.shouldGenerate(options, type);

  @override
  List<Error> validate(PigeonOptions options, Root root) =>
      delegate.validate(options, _withoutEventChannels(root));

  @override
  void generate(
    StringSink sink,
    PigeonOptions options,
    Root root,
    FileType type,
  ) => delegate.generate(sink, options, _withoutEventChannels(root), type);
}

Future<void> main() async {
  const input = 'pigeon/messages.dart';
  final parsed = Pigeon.setup().parseFile(input);
  if (parsed.errors.isNotEmpty) {
    Pigeon.printErrors(parsed.errors);
    exitCode = 1;
    return;
  }
  final options = PigeonOptions.fromMap({
    ...parsed.pigeonOptions!,
    'input': input,
  });
  final result = await Pigeon.runWithOptions(
    options,
    adapters: [
      DartGeneratorAdapter(),
      KotlinGeneratorAdapter(),
      SwiftGeneratorAdapter(),
      DesktopGeneratorAdapter(CppGeneratorAdapter()),
      DesktopGeneratorAdapter(GObjectGeneratorAdapter()),
    ],
  );
  if (result != 0) {
    exitCode = result;
    return;
  }

  // The Swift generator includes conditional Flutter/FlutterMacOS imports.
  final macosFile = File(configuration.macosSwiftOut);
  macosFile.parent.createSync(recursive: true);
  macosFile.writeAsBytesSync(File(options.swiftOut!).readAsBytesSync());

  // Derive Linux custom type tags from the same model list as every codec.
  final types = StringBuffer(
    '// Generated by tool/generate_pigeon.dart. Do not edit.\n'
    '#pragma once\n\n',
  );
  for (final type in getEnumeratedTypes(
    parsed.root,
    excludeSealedClasses: true,
  )) {
    types.writeln('constexpr int k${type.name}Type = ${type.enumeration};');
  }
  final typesFile = File(
    '${File(options.gobjectHeaderOut!).parent.path}/message_types.g.h',
  );
  typesFile.writeAsStringSync(types.toString());
}
